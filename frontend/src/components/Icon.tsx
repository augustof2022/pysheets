export default function Icon({ name, size = 16, className }: { name?: string; size?: number; className?: string }) {
  if (!name) return <span className="icon-spacer" style={{ width: size }} />;
  const C = MAP[name];
  if (!C) return <span className="icon-spacer" style={{ width: size }} />;
  return <C size={size} strokeWidth={1.75} className={className} />;
}
